    def enqueue_wake(self, *, target_agent: str, task: dict[str, Any], priority: int = 0) -> int:
        with self._connect() as conn:
            cursor = conn.execute(
                "INSERT INTO agent_wake_queue (target_agent, task_json, priority) VALUES (?, ?, ?)",
                (target_agent.strip(), json.dumps(task, ensure_ascii=True, default=str), priority),
            )
            return int(cursor.lastrowid)

    def claim_wake_item(self, *, target_agent: str, claimer_pid: int) -> dict[str, Any] | None:
        """Atomically claim the highest-priority unclaimed wake item for a given agent."""
        now = _utc_now_db()
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            row = conn.execute(
                """
                SELECT id, task_json FROM agent_wake_queue
                WHERE target_agent = ? AND claimed_at = ''
                ORDER BY priority DESC, id ASC
                LIMIT 1
                """,
                (target_agent.strip(),),
            ).fetchone()
            if not row:
                conn.rollback()
                return None
            conn.execute(
                "UPDATE agent_wake_queue SET claimed_at = ?, claimer_pid = ? WHERE id = ?",
                (now, claimer_pid, row["id"]),
            )
            conn.commit()
        return {"id": int(row["id"]), "task": _normalize_jsonish(row["task_json"] or "{}"), "claimed_at": now}

    def list_wake_queue(self, *, target_agent: str = "", include_claimed: bool = False) -> list[dict[str, Any]]:
        query = "SELECT * FROM agent_wake_queue"
        conditions: list[str] = []
        params: list[Any] = []
        if target_agent.strip():
            conditions.append("target_agent = ?")
            params.append(target_agent.strip())
        if not include_claimed:
            conditions.append("claimed_at = ''")
        if conditions:
            query += " WHERE " + " AND ".join(conditions)
        query += " ORDER BY priority DESC, id ASC"
        with self._connect() as conn:
            rows = conn.execute(query, params).fetchall()
        return [
            {
                "id": row["id"],
                "target_agent": row["target_agent"],
                "task": _normalize_jsonish(row["task_json"] or "{}"),
                "priority": row["priority"],
                "enqueued_at": row["enqueued_at"],
                "claimed_at": row["claimed_at"] or None,
                "claimer_pid": row["claimer_pid"],
            }
            for row in rows
        ]

