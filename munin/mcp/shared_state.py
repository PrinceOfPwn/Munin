def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


def _utc_now_db() -> str:
    return _utc_now().replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _lease_until(seconds: int) -> str:
    return (_utc_now() + timedelta(seconds=seconds)).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _normalize_jsonish(raw: str) -> Any:
    text = (raw or "").strip()
    if not text:
        return {}
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return {"raw": text}


def _normalize_tags(raw: str) -> list[str]:
    tags: list[str] = []
    for item in (raw or "").replace(",", "\n").splitlines():
        value = item.strip()
        if value:
            tags.append(value)
    return tags


@dataclass(frozen=True)
class SharedTaskDecision:
    success: bool
    message: str
    task_id: int | None = None
    stolen_stale_task_id: int | None = None


class SharedStateStore:
    """SQLite-backed shared state used by ALL Munin agents.

    Tables:
      - shared_intel        (OFFX original) findings shared across agents
      - active_tasks        (OFFX original) exclusive task locks with leases
      - agent_presence      (OFFX original) wake/sleep registry
      - agent_messages      (OFFX original) inter-agent inbox
      - episodic            (Munin new)     every tool call, ReAct step, decision
      - semantic            (Munin new)     facts Munin remembers
      - procedural          (Munin new)     autogenerated tools registry
      - generated_graphs    (Munin new)     forged ReAct graph specs
      - agent_wake_queue    (Munin new)     orchestrator → subagent wake channel
    """

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.db_path = settings.shared_state_db
        ensure_parent(self.db_path)
        self._init_db()

    # ------------------------------------------------------------------
    # Connection / schema
    # ------------------------------------------------------------------
    def _connect(self) -> sqlite3.Connection:
        conn = sqlite3.connect(str(self.db_path), timeout=30)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA journal_mode=WAL")
        conn.execute("PRAGMA synchronous=NORMAL")
        conn.execute("PRAGMA foreign_keys=ON")
        conn.execute("PRAGMA busy_timeout=30000")
        return conn

    def _init_db(self) -> None:
        with self._connect() as conn:
            conn.executescript(
                """
                -- OFFX-original tables
                CREATE TABLE IF NOT EXISTS shared_intel (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    target_ip TEXT NOT NULL,
                    port INTEGER,
                    service TEXT,
                    finding_type TEXT NOT NULL,
                    severity TEXT,
                    details TEXT NOT NULL DEFAULT '{}',
                    source_agent TEXT,
                    status TEXT NOT NULL DEFAULT 'NEW',
                    tags TEXT NOT NULL DEFAULT '[]',
                    fingerprint TEXT NOT NULL DEFAULT '',
                    timestamp TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
                );

                CREATE TABLE IF NOT EXISTS active_tasks (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    target_ip TEXT NOT NULL,
                    action TEXT NOT NULL,
                    task_key TEXT NOT NULL,
                    assigned_agent TEXT NOT NULL,
                    status TEXT NOT NULL,
                    lease_expires_at TEXT NOT NULL,
                    metadata TEXT NOT NULL DEFAULT '{}',
                    result TEXT NOT NULL DEFAULT '{}',
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
                );

                CREATE TABLE IF NOT EXISTS agent_presence (
                    agent_name TEXT PRIMARY KEY,
                    role TEXT NOT NULL DEFAULT '',
                    status TEXT NOT NULL DEFAULT 'IDLE',
                    current_task_id INTEGER,
                    last_seen_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    metadata TEXT NOT NULL DEFAULT '{}',
                    FOREIGN KEY(current_task_id) REFERENCES active_tasks(id)
                );

                CREATE TABLE IF NOT EXISTS agent_messages (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    sender_agent TEXT NOT NULL,
                    recipient_agent TEXT NOT NULL,
                    subject TEXT NOT NULL DEFAULT '',
                    message_type TEXT NOT NULL DEFAULT 'INFO',
                    body TEXT NOT NULL DEFAULT '',
                    related_task_id INTEGER,
                    related_target_ip TEXT NOT NULL DEFAULT '',
                    status TEXT NOT NULL DEFAULT 'NEW',
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    read_at TEXT NOT NULL DEFAULT '',
                    metadata TEXT NOT NULL DEFAULT '{}',
                    FOREIGN KEY(related_task_id) REFERENCES active_tasks(id)
                );

                -- Munin-new tables
                CREATE TABLE IF NOT EXISTS episodic (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    ts TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    agent TEXT NOT NULL,
                    action TEXT NOT NULL,
                    input_json TEXT NOT NULL DEFAULT '{}',
                    output_json TEXT NOT NULL DEFAULT '{}',
                    tags TEXT NOT NULL DEFAULT '[]'
                );

                CREATE TABLE IF NOT EXISTS semantic (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    key TEXT NOT NULL UNIQUE,
                    value_json TEXT NOT NULL DEFAULT '{}',
                    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
                );

                CREATE TABLE IF NOT EXISTS procedural (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL UNIQUE,
                    description TEXT NOT NULL DEFAULT '',
                    script_path TEXT NOT NULL,
                    signature_json TEXT NOT NULL DEFAULT '{}',
                    tags TEXT NOT NULL DEFAULT '[]',
                    created_by_agent TEXT NOT NULL DEFAULT '',
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    active INTEGER NOT NULL DEFAULT 1
                );

                CREATE TABLE IF NOT EXISTS generated_graphs (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL UNIQUE,
                    purpose TEXT NOT NULL DEFAULT '',
                    system_prompt TEXT NOT NULL DEFAULT '',
                    tool_whitelist_json TEXT NOT NULL DEFAULT '[]',
                    reset_policy TEXT NOT NULL DEFAULT 'on_reset',
                    created_by_agent TEXT NOT NULL DEFAULT '',
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    active INTEGER NOT NULL DEFAULT 1
                );

                CREATE TABLE IF NOT EXISTS agent_wake_queue (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    target_agent TEXT NOT NULL,
                    task_json TEXT NOT NULL DEFAULT '{}',
                    priority INTEGER NOT NULL DEFAULT 0,
                    enqueued_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    claimed_at TEXT NOT NULL DEFAULT '',
                    claimer_pid INTEGER
                );

                -- Indexes
                CREATE INDEX IF NOT EXISTS idx_shared_intel_target ON shared_intel(target_ip);
                CREATE INDEX IF NOT EXISTS idx_shared_intel_service ON shared_intel(service);
                CREATE INDEX IF NOT EXISTS idx_shared_intel_type ON shared_intel(finding_type);
                CREATE INDEX IF NOT EXISTS idx_active_tasks_target ON active_tasks(target_ip);
                CREATE INDEX IF NOT EXISTS idx_active_tasks_agent ON active_tasks(assigned_agent);
                CREATE INDEX IF NOT EXISTS idx_agent_messages_recipient ON agent_messages(recipient_agent, status, created_at);
                CREATE INDEX IF NOT EXISTS idx_agent_messages_task ON agent_messages(related_task_id);
                CREATE UNIQUE INDEX IF NOT EXISTS ux_active_task_running
                    ON active_tasks(task_key)
                    WHERE status = 'RUNNING';

                CREATE INDEX IF NOT EXISTS idx_episodic_agent_ts ON episodic(agent, ts DESC);
                CREATE INDEX IF NOT EXISTS idx_episodic_action ON episodic(action);
                CREATE INDEX IF NOT EXISTS idx_procedural_name ON procedural(name);
                CREATE INDEX IF NOT EXISTS idx_procedural_active ON procedural(active);
                CREATE INDEX IF NOT EXISTS idx_generated_graphs_active ON generated_graphs(active);
                CREATE INDEX IF NOT EXISTS idx_agent_wake_queue_target ON agent_wake_queue(target_agent, claimed_at);
                """
            )

    # ------------------------------------------------------------------
    # shared_intel (unchanged)
    # ------------------------------------------------------------------
    def publish_intel(
        self,
        *,
        target_ip: str,
        port: int | None,
        service: str,
        finding_type: str,
        severity: str,
        details_json: str,
        source_agent: str,
        status: str,
        tags: str,
        fingerprint: str,
    ) -> dict[str, Any]:
        now = _utc_now_db()
        details = _normalize_jsonish(details_json)
        tag_list = _normalize_tags(tags)
        with self._connect() as conn:
            cursor = conn.execute(
                """
                INSERT INTO shared_intel (
                    target_ip, port, service, finding_type, severity, details,
                    source_agent, status, tags, fingerprint, timestamp, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    target_ip.strip(),
                    port,
                    service.strip(),
                    finding_type.strip(),
                    severity.strip() or "INFO",
                    json.dumps(details, ensure_ascii=True),
                    source_agent.strip(),
                    status.strip() or "NEW",
                    json.dumps(tag_list, ensure_ascii=True),
                    fingerprint.strip(),
                    now,
                    now,
                ),
            )
            intel_id = int(cursor.lastrowid)
        return {
            "intel_id": intel_id,
            "target_ip": target_ip.strip(),
            "finding_type": finding_type.strip(),
            "service": service.strip(),
            "severity": severity.strip() or "INFO",
            "source_agent": source_agent.strip(),
            "status": status.strip() or "NEW",
            "tags": tag_list,
            "timestamp": now,
        }

    def query_intel(
        self,
        *,
        target_ip: str = "",
        service: str = "",
        finding_type: str = "",
        severity: str = "",
        status: str = "",
        limit: int = 50,
    ) -> list[dict[str, Any]]:
        query = "SELECT * FROM shared_intel WHERE 1=1"
        params: list[Any] = []
        if target_ip.strip():
            query += " AND target_ip = ?"
            params.append(target_ip.strip())
        if service.strip():
            query += " AND service = ?"
            params.append(service.strip())
        if finding_type.strip():
            query += " AND finding_type = ?"
            params.append(finding_type.strip())
        if severity.strip():
            query += " AND severity = ?"
            params.append(severity.strip())
        if status.strip():
            query += " AND status = ?"
            params.append(status.strip())
        query += " ORDER BY timestamp DESC LIMIT ?"
        params.append(max(1, min(limit, 500)))
        with self._connect() as conn:
            rows = conn.execute(query, params).fetchall()
        return [self._intel_row_to_dict(row) for row in rows]

    # ------------------------------------------------------------------
    # active_tasks (unchanged)
    # ------------------------------------------------------------------
    def claim_task(
        self,
        *,
        target_ip: str,
        action: str,
        assigned_agent: str,
        lease_seconds: int,
        metadata_json: str,
        allow_steal_stale: bool,
    ) -> SharedTaskDecision:
        now = _utc_now_db()
        task_key = self._task_key(target_ip, action)
        metadata = _normalize_jsonish(metadata_json)
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            row = conn.execute(
                """
                SELECT id, assigned_agent, lease_expires_at
                FROM active_tasks
                WHERE task_key = ? AND status = 'RUNNING'
                """,
                (task_key,),
            ).fetchone()
            stolen_task_id: int | None = None
            if row:
                lease_expires_at = row["lease_expires_at"] or ""
                stale = bool(lease_expires_at and lease_expires_at < now)
                if not stale or not allow_steal_stale:
                    conn.rollback()
                    return SharedTaskDecision(
                        success=False,
                        message=f"task already running for {task_key} by {row['assigned_agent']}",
                    )
                stolen_task_id = int(row["id"])
                conn.execute(
                    """
                    UPDATE active_tasks
                    SET status = 'STALE', updated_at = ?, result = ?
                    WHERE id = ?
                    """,
                    (
                        now,
                        json.dumps({"reason": "stolen_after_stale_lease"}, ensure_ascii=True),
                        stolen_task_id,
                    ),
                )
            cursor = conn.execute(
                """
                INSERT INTO active_tasks (
                    target_ip, action, task_key, assigned_agent, status,
                    lease_expires_at, metadata, result, created_at, updated_at
                ) VALUES (?, ?, ?, ?, 'RUNNING', ?, ?, '{}', ?, ?)
                """,
                (
                    target_ip.strip(),
                    action.strip(),
                    task_key,
                    assigned_agent.strip(),
                    _lease_until(max(30, lease_seconds)),
                    json.dumps(metadata, ensure_ascii=True),
                    now,
                    now,
                ),
            )
            task_id = int(cursor.lastrowid)
            conn.commit()
        return SharedTaskDecision(
            success=True,
            message=f"task claimed by {assigned_agent.strip()}",
            task_id=task_id,
            stolen_stale_task_id=stolen_task_id,
        )

    def heartbeat_task(self, *, task_id: int, assigned_agent: str, lease_seconds: int) -> dict[str, Any]:
        now = _utc_now_db()
        with self._connect() as conn:
            row = conn.execute(
                "SELECT id, assigned_agent, status FROM active_tasks WHERE id = ?",
                (task_id,),
            ).fetchone()
            if not row:
                return {"success": False, "message": f"task {task_id} not found"}
            if row["assigned_agent"] != assigned_agent.strip():
                return {"success": False, "message": f"task {task_id} owned by {row['assigned_agent']}"}
            if row["status"] != "RUNNING":
                return {"success": False, "message": f"task {task_id} is {row['status']}"}
            lease_expires_at = _lease_until(max(30, lease_seconds))
            conn.execute(
                "UPDATE active_tasks SET lease_expires_at = ?, updated_at = ? WHERE id = ?",
                (lease_expires_at, now, task_id),
            )
        return {"success": True, "message": "heartbeat updated", "task_id": task_id, "lease_expires_at": lease_expires_at}

    def complete_task(self, *, task_id: int, assigned_agent: str, status: str, result_json: str) -> dict[str, Any]:
        final_status = status.strip().upper() or "COMPLETED"
        if final_status not in {"COMPLETED", "FAILED", "CANCELLED"}:
            final_status = "COMPLETED"
        now = _utc_now_db()
        with self._connect() as conn:
            row = conn.execute("SELECT id, assigned_agent FROM active_tasks WHERE id = ?", (task_id,)).fetchone()
            if not row:
                return {"success": False, "message": f"task {task_id} not found"}
            if row["assigned_agent"] != assigned_agent.strip():
                return {"success": False, "message": f"task {task_id} owned by {row['assigned_agent']}"}
            conn.execute(
                "UPDATE active_tasks SET status = ?, result = ?, updated_at = ?, lease_expires_at = ? WHERE id = ?",
                (
                    final_status,
                    json.dumps(_normalize_jsonish(result_json), ensure_ascii=True),
                    now,
                    now,
                    task_id,
                ),
            )
        return {"success": True, "message": f"task {task_id} marked {final_status}", "task_id": task_id, "status": final_status}

