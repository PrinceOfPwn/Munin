"""Munin — the main ReAct agent.

Loops:
  1. Read soul (identity + principles + goals + skills) into system prompt.
  2. Append memory summary + generated-tools catalog (dynamic — refreshed each iteration).
  3. Ask the LLM using OpenAI tool-calling with the exposed tool catalog.
  4. Execute the tool the LLM picked. Log episodic. Feed result back.
  5. Continue until the LLM stops calling tools or the max_iterations budget is spent.

The tool catalog contains a hand-picked selection of native MCP tools (LDAP, Hugin,
Tavily, wake/sleep, memory, forge) PLUS every `gen__*` autogenerated tool. The
autogenerated ones are re-enumerated on every turn — so a tool Munin forges mid-loop
becomes available in the very next step.

v3.1.1 hardening (source edit — no monkey-patch):
  * ``respond`` accepts an optional ``pre_iteration_hook: Callable[[int], str | None]``
    which is invoked at the top of every ReAct iteration.  Non-empty return
    values are appended to the message list as a ``system`` message using an
    ``<operator_guidance>`` wrapper so the model can act on it in the next
    step.  The signature keeps backwards compatibility — callers that don't
    pass the kwarg behave exactly like before.
  * When the model returns more than one ``tool_use`` block in the same
    assistant message, the batch is dispatched through
    :func:`munin.production.parallel.execute_tool_batch`.  Read-only /
    idempotent tools declared in ``PARALLEL_SAFE_TOOLS`` run concurrently
    through a ``ThreadPoolExecutor`` bounded by ``MUNIN_MAX_PARALLEL_TOOLS``;
    everything else stays serial.  ``parallel_group_id`` is stamped on the
    ``tool_start`` / ``tool_result`` progress events so the dispatcher can
    correlate the batch on the ``tool_calls`` row.
  * When ``pre_iteration_hook`` is ``None`` and the model emits at most one
    tool_use per iteration, execution is byte-identical to the pre-v3.1.1
    behaviour so existing tests, ad-hoc scripts and legacy callers keep
    working without changes.
"""

